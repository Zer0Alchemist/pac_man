    GLYPH_W, GLYPH_H = 5, 7

    def __init__(self , screen : pygame.Surface , size):

        self.screen = screen
        self.WIDTH , self.HEIGHT = size


    def __draw_pixel_block(self,x , y , color , scale) :
        for block_y in range(scale):
            for block_x in range(scale):
                self.screen.set_at((x + block_x , y + block_y ) , color)


    def __draw_char(self,glyph, x, y, scale, color):
        for row_index, row_data in enumerate(glyph):

            for col_index in range(self.GLYPH_W):
                bit_position = self.GLYPH_W - 1 - col_index
                pixel = ( row_data >> bit_position ) & 1
                if pixel == 1:

                    pixel_x = x + col_index * scale
                    pixel_y = y + row_index * scale

                    self.__draw_pixel_block(
                        pixel_x,
                        pixel_y,
                        color,
                        scale
                    )


    def __get_text_width(self, text , scale) -> int:
        return len(text) * ( self.GLYPH_W * scale ) + (scale * (len(text) - 1 ))

    def __draw_text(self , text , x , y , scale , color) :
        for ch in text :
            bit_map = self.GLYPHS.get(ch.upper() , None)
            if bit_map is not None :
                self.__draw_char(bit_map , x , y , scale , color)
            x += (self.GLYPH_W + 1) * scale  

    def draw_centered_text(self , text , y , color , scale):
            starting_x =  (self.WIDTH - self.__get_text_width(text , scale)) // 2
            self.__draw_text(text , starting_x , y , scale , color)
