"""Drawing helpers built only on calls that MiniLibX also has.

pygame calls used: Surface(), Surface.set_at(), blit onto the window,
image.load(). Rectangles, circles and text are built from pixel writes.
"""
from __future__ import annotations

from pathlib import Path

import pygame

Color = tuple[int, int, int]


class GfxError(Exception):
    """Raised when an image cannot be loaded."""


class Image:
    """An off-screen picture (mlx_new_image)."""

    def __init__(self, surface: pygame.Surface) -> None:
        self.surface = surface
        self.width, self.height = surface.get_size()

    def pixel(self, x: int, y: int, color: Color) -> None:
        """Write one pixel (mlx_pixel_put)."""
        if 0 <= x < self.width and 0 <= y < self.height:
            self.surface.set_at((x, y), color)

    def fill_rect(self, x: int, y: int, w: int, h: int, color: Color) -> None:
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(self.width, x + w), min(self.height, y + h)
        for py in range(y0, y1):
            for px in range(x0, x1):
                self.surface.set_at((px, py), color)

    def fill_circle(self, cx: int, cy: int, radius: int,
                    color: Color) -> None:
        for py in range(cy - radius, cy + radius + 1):
            for px in range(cx - radius, cx + radius + 1):
                if (px - cx) ** 2 + (py - cy) ** 2 <= radius ** 2:
                    self.pixel(px, py, color)


def new_image(width: int, height: int, transparent: bool = True) -> Image:
    """Create an empty image. Transparent ones start fully see-through."""
    flags = pygame.SRCALPHA if transparent else 0
    return Image(pygame.Surface((width, height), flags))


def load_image(path: Path) -> Image:
    """Load a PNG/XPM file (mlx_xpm_file_to_image)."""
    try:
        return Image(pygame.image.load(str(path)))
    except (pygame.error, OSError) as error:
        raise GfxError(f"cannot load {path}: {error}") from error


def put_image(window: pygame.Surface, image: Image, x: int, y: int) -> None:
    """Show an image on the window (mlx_put_image_to_window)."""
    window.blit(image.surface, (x, y))


